/** 남은 시간 비율(1→0)로 지금 단계의 배율을 고른다. 단계 사이는 화면에서 짧게 부드럽게 바뀐다. */
export function zoomStepScale(remainingRatio, steps = ZOOM_STEPS) {
  const elapsed = 1 - Math.min(1, Math.max(0, Number(remainingRatio) || 0));
  let scale = steps[0][1];
  for (const [at, value] of steps) if (elapsed >= at) scale = value;
  return scale;
}

/** 확대 초점은 사진 가운데 근처(가로·세로 30~70%)에서 고른다. 값은 백분율. */
export function pickZoomFocus(rand = Math.random) {
  const pick = () => Math.round((30 + rand() * 40) * 10) / 10;
  return { x: pick(), y: pick() };
}

export function buildZoomPool(raw = {}) {
  const seen = new Set();
  const items = [];
  for (const row of Array.isArray(raw?.items) ? raw.items : []) {
    const word = String(row?.word || "").trim();
    const image = String(row?.image || "").trim();
    if (!word || !/^https:\/\//.test(image) || seen.has(word)) continue;
    seen.add(word);
    const aliases = Array.isArray(row.aliases) ? row.aliases.map((name) => String(name || "").trim()).filter(Boolean) : [];
    items.push({ word, genre: String(row.genre || "").trim(), image, aliases });
  }
  return { fetchedAt: Number(raw?.fetchedAt) || 0, items };
}

/** genres 가 비었거나 없으면 전체. */
export function filterZoomEntries(pool, genres = null) {
  const pick = Array.isArray(genres) && genres.length ? new Set(genres) : null;
  return (pool?.items || []).filter((row) => !pick || pick.has(row.genre));
}

export function pickZoomEntries(pool, { exclude, genres } = {}, count = 1) {
  const n = Math.max(1, Math.min(3, Math.floor(Number(count) || 1)));
  const all = filterZoomEntries(pool, genres);
  let left = exclude instanceof Set ? all.filter((row) => !exclude.has(row.word)) : all.slice();
  if (!left.length && all.length && exclude instanceof Set) {
    for (const row of all) exclude.delete(row.word);
    left = all.slice();
  }
  if (!left.length) throw new Error("낼 사진이 없습니다");
  const out = [];
  while (out.length < n && left.length) {
    out.push(left.splice(Math.floor(Math.random() * left.length), 1)[0]);
  }
  return out;
}

export async function loadZoomPool(fetchImpl = fetch) {
  try {
    const res = await fetchImpl(ZOOM_URL, { cache: "no-cache" });
    if (!res.ok) throw new Error(`zoom ${res.status}`);
    return buildZoomPool(await res.json());
  } catch {
    return buildZoomPool({});
  }
}
