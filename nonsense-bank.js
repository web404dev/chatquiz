const ANSWER_RE = /^[가-힣0-9A-Za-z]+( [가-힣0-9A-Za-z]+)*$/;

export function buildNonsensePool(items = NONSENSE_ITEMS) {
  const seen = new Set();
  const out = [];
  for (const row of items) {
    const word = String(row?.word || "").trim();
    const question = String(row?.question || "").trim();
    if (!ANSWER_RE.test(word) || !question || seen.has(question)) continue;
    seen.add(question);
    const aliases = (row.aliases || []).map((name) => String(name || "").trim()).filter((name) => ANSWER_RE.test(name));
    out.push({ key: `nonsense:${question}`, genre: "", source: String(row.source || ""), word, question, aliases, level: "" });
  }
  return { fetchedAt: 0, items: out };
}

export function pickNonsenseEntries(pool, { exclude } = {}, count = 1) {
  const n = Math.max(1, Math.min(3, Math.floor(Number(count) || 1)));
  const all = (pool?.items || []).slice();
  let left = exclude instanceof Set ? all.filter((row) => !exclude.has(row.key)) : all.slice();
  if (!left.length && all.length && exclude instanceof Set) {
    for (const row of all) exclude.delete(row.key);
    left = all.slice();
  }
  if (!left.length) throw new Error("낼 넌센스 문제가 없습니다");
  const out = [];
  while (out.length < n && left.length) out.push(left.splice(Math.floor(Math.random() * left.length), 1)[0]);
  return out;
}

